"""Качество импульса: скорость, ускорение, свежесть экстремума, удержание.

Зачем это отдельно. Старый триггер задавал один вопрос — «прошёл ли рынок
достаточное расстояние?» — и три совершенно разные ситуации выглядели для
него одинаково:

  * $5 за 0.1с с продолжением — сильный импульс;
  * $5 за 15с — плавный дрейф, который книга давно переоценила;
  * $5 за 0.2с с мгновенным откатом — ложный вынос ликвидности.

Здесь движение описывается ЧЕТЫРЬМЯ независимыми величинами, и решение
принимает стратегия по их сочетанию, а не по одной дистанции:

  jump_usd  — знаковое смещение от локального экстремума, $;
  age_s     — возраст этого экстремума (старое дно не имеет отношения к
              текущему движению);
  speed     — скорость цены за последнюю секунду, $/с (знаковая);
  accel     — идёт ли движение своим темпом: текущая скорость, делённая
              на СРЕДНЮЮ скорость самого импульса (>1 разгон, <1 встало);
  hold      — какую долю хода цена удержала (1.0 — стоит на пике,
              0.0 — вернулась в точку старта: вынос ликвидности).

Трекер только СЧИТАЕТ. Порогов и решений здесь нет — они в стратегии, где
их можно прогонять через replay с любыми значениями.
"""
from __future__ import annotations

from collections import deque
from dataclasses import dataclass
from typing import Deque, Optional, Tuple

# Сетка выборки. Чаще нет смысла: консенсус цен сам обновляется ~20 Гц,
# а решения принимаются на каждом событии книги.
_SAMPLE_S = 0.05

# Окно скорости. Константа, а не настройка: это определение величины
# «скорость», а не порог стратегии.
_SPEED_S = 1.0          # скорость = движение за эту последнюю секунду


@dataclass
class ImpulseState:
    jump_usd: float     # знаковое движение от экстремума (+вверх, −вниз)
    age_s: float        # сколько секунд назад был этот экстремум
    speed: float        # $/с за последнюю секунду, знаковая
    accel: float        # >1 разгоняется, <1 затухает, <=0 развернулась
    hold: float         # доля удержанного хода [0..1]


class ImpulseTracker:
    """Скользящее описание последнего движения цены. Без порогов, без I/O."""

    def __init__(self, lookback_s: float = 15.0):
        self.lookback_s = float(lookback_s)
        # Храним чуть больше окна поиска экстремума: ускорению нужен хвост.
        self._keep_s = self.lookback_s + 2.0
        self._pts: Deque[Tuple[float, float]] = deque()

    # ------------------------------------------------------------------
    def feed(self, t_s: float, price: Optional[float]) -> None:
        if price is None:
            return
        pts = self._pts
        if pts and t_s - pts[-1][0] < _SAMPLE_S:
            return
        pts.append((t_s, float(price)))
        while pts and t_s - pts[0][0] > self._keep_s:
            pts.popleft()

    def reset(self, t_s: float, price: Optional[float]) -> None:
        """Забыть историю: движение отработано сделкой, экстремум не должен
        секунду спустя открыть ещё одну такую же."""
        self._pts.clear()
        if price is not None:
            self._pts.append((t_s, float(price)))

    # ------------------------------------------------------------------
    def _price_at(self, when: float) -> Optional[float]:
        """Цена в момент `when` (ближайшая точка не позже него)."""
        best = None
        for t, p in self._pts:
            if t <= when:
                best = p
            else:
                break
        return best

    def state(self) -> Optional[ImpulseState]:
        pts = self._pts
        if len(pts) < 3:
            return None
        t_now, p_now = pts[-1]
        if t_now - pts[0][0] < _SPEED_S:
            return None                       # истории меньше секунды

        # --- экстремумы окна поиска --------------------------------------
        lo_t = hi_t = t_now
        lo_p = hi_p = p_now
        for t, p in pts:
            if t_now - t > self.lookback_s:
                continue
            # `<=`, а не `<`: если цена стояла на дне две секунды и лишь
            # потом пошла, движение началось в ПОСЛЕДНЕЙ точке дна, а не в
            # первой. Со строгим сравнением свежий рывок получал бы возраст
            # всей полки и отсекался как «старый экстремум».
            if p <= lo_p:
                lo_p, lo_t = p, t
            if p >= hi_p:
                hi_p, hi_t = p, t

        up = p_now - lo_p                     # рост от дна
        down = hi_p - p_now                   # падение от пика
        if up >= down:
            jump, ext_t, ext_p = up, lo_t, lo_p
        else:
            jump, ext_t, ext_p = -down, hi_t, hi_p
        age = t_now - ext_t

        # --- скорость -----------------------------------------------------
        p_1s = self._price_at(t_now - _SPEED_S)
        speed = (p_now - p_1s) / _SPEED_S if p_1s is not None else 0.0

        # --- ускорение ----------------------------------------------------
        # Отношение ТЕКУЩЕЙ скорости к СРЕДНЕЙ скорости самого импульса:
        # «движение идёт своим темпом или уже встало?». Величина безразмерна
        # и не зависит от масштаба движения.
        #
        # Сравнивать два фиксированных окна («последние 0.5с против
        # предыдущих 1.5с») нельзя: рывок на $5 за 0.4 секунды целиком
        # попадает в СТАРОЕ окно, в свежем остаётся спокойный хвост, и
        # сильный ход, который завершился и держится, выглядел бы
        # затухающим. Это ровно тот случай, который нужно ПОКУПАТЬ.
        #
        # Средняя берётся минимум за окно скорости: если весь ход занял
        # 0.3с, скорость за секунду уже включает его целиком, и делить одно
        # на другое надо в одинаковых единицах, иначе самые быстрые
        # движения штрафовались бы сильнее всех.
        sign = 1.0 if jump >= 0 else -1.0
        avg_speed = abs(jump) / max(age, _SPEED_S)
        accel = (sign * speed) / avg_speed if avg_speed > 1e-9 else 1.0

        # --- удержание хода ----------------------------------------------
        # Пик движения ПОСЛЕ экстремума: докуда цена доходила. Если сейчас
        # мы сильно ниже этого пика (для роста), большая часть хода отдана
        # назад — это и есть ложный вынос.
        peak = ext_p
        for t, p in pts:
            if t < ext_t:
                continue
            if jump >= 0:
                peak = max(peak, p)
            else:
                peak = min(peak, p)
        # ДИАПАЗОН hold — [0.5, 1.0], и это следует из выбора направления,
        # а не из данных. Направление берётся по большему из двух смещений,
        # поэтому «удержано меньше половины» невозможно: как только откат
        # переваливает 50%, обратное движение становится доминирующим и
        # трекер описывает уже ЕГО (свежий откат, удержанный полностью).
        # Отсюда: порог ниже 0.5 не фильтрует ничего, осмысленные значения
        # начинаются с 0.6-0.8.
        full = abs(peak - ext_p)
        hold = abs(p_now - ext_p) / full if full > 1e-9 else 1.0
        hold = max(0.0, min(1.0, hold))

        return ImpulseState(jump_usd=jump, age_s=age, speed=speed,
                            accel=accel, hold=hold)
