"""Оценки признаков входа: каждый признак даёт 0..1, а не «да/нет».

Зачем это заменило жёсткие ворота. В v22 вход проходил восемь обязательных
проверок, и провал ЛЮБОЙ означал отказ. На бумаге строго, на практике —
сделок почти не стало: движение сильное, скорость высокая, запас хороший, а
возраст импульса 8.2 секунды вместо 8.0 — и вход отменён целиком. Один
признак, промахнувшийся на 2%, перечёркивал остальные пять.

Здесь каждый признак отвечает не «можно/нельзя», а «насколько хорошо»:

    ход 2.5σ -> 1.0      ход 2.0σ -> 0.8      ход 1.6σ -> 0.4

Дальше оценки складываются с весами в общий Score от 0 до 1, и решение
принимается ОДИН раз — по нему. Слегка просевший признак теперь снижает
качество сделки, а не отменяет её.

ГРАНИЦА, КОТОРАЯ ОСТАЛАСЬ ЖЁСТКОЙ. Ноль в этих шкалах означает не «слабо»,
а «так не бывает у сигнала, который мы хотим»: удержание ниже 60% — это
вынос ликвидности, ход меньше 1.5σ — это шум, скорость ниже 0.7σ — движение
уже кончилось. Поэтому ноль по любому признаку по умолчанию отменяет вход
(`JUMP_SCORE_VETO_ZERO`), иначе средневзвешенное 0.89 спокойно покупало бы
ровно тот вынос ликвидности, ради отсева которого вся эта конструкция и
строилась. Всё, что СТРОГО БОЛЬШЕ нуля, не блокирует ничего и работает
только через вес.

Шкалы заданы таблицами, а не формулами, — их надо перебирать по записи
(`replay.py --sweep score-min ...`), а не выводить из общих соображений.
Все пороги ниже — догадки той же природы, что и прежние.
"""
from __future__ import annotations

from typing import Optional, Sequence, Tuple

# Таблица: (порог, оценка), по убыванию порога. Первое совпадение выигрывает.
Table = Sequence[Tuple[float, float]]

# --- «больше — лучше» -------------------------------------------------------
JUMP_SIGMAS: Table = ((2.5, 1.0), (2.2, 0.9), (2.0, 0.8), (1.8, 0.6),
                      (1.5, 0.4))
SPEED_SIGMAS: Table = ((1.5, 1.0), (1.3, 0.9), (1.1, 0.8), (0.9, 0.6),
                       (0.7, 0.4))
HOLD: Table = ((0.95, 1.0), (0.90, 0.9), (0.80, 0.8), (0.70, 0.6),
               (0.60, 0.3))
ACCEL: Table = ((1.2, 1.0), (1.0, 0.9), (0.8, 0.7), (0.6, 0.5), (0.4, 0.2))
EDGE_CENTS: Table = ((6.0, 1.0), (5.0, 0.9), (4.0, 0.8), (3.0, 0.6),
                     (2.0, 0.3))
# Ожидаемый сдвиг процента: шкала своей формой повторяет запас — обе величины
# в центах и обе отвечают на вопрос «есть ли тут вообще что забирать».
SHIFT_CENTS: Table = ((6.0, 1.0), (4.0, 0.9), (3.0, 0.8), (2.0, 0.6),
                      (1.0, 0.3))

# --- «меньше — лучше» -------------------------------------------------------
# Возраст импульса: чем дольше идёт движение, тем ближе вход к его концу.
AGE_S: Table = ((4.0, 1.0), (6.0, 0.9), (8.0, 0.7), (10.0, 0.5), (12.0, 0.2))


def scaled(table: Table, factor: float) -> Table:
    """Та же шкала, растянутая под другой опорный порог.

    Зачем. Формы шкал выше сняты с прежних жёстких порогов: 2.0σ по ходу,
    1.0σ/с по скорости, 70% удержания, 8с возраста, 3¢ запаса. Но сами эти
    опорные значения — догадки, и подбирать их надо перебором. Растягивая
    таблицу, а не переписывая её, мы сохраняем ФОРМУ («на пороге ~0.6-0.8,
    заметно лучше порога — 1.0») и продолжаем крутить одну ручку.

    Отдельно это возвращает спред в расчёт запаса. Абсолютная шкала «≥6¢ =
    отлично» неверна ровно там, где спред не 1¢, а 5: тогда 6¢ запаса — это
    полтора цента после круга. Опорный порог запаса считается как
    max(база, множитель × спред), и шкала едет вместе с ним.
    """
    if factor <= 0 or abs(factor - 1.0) < 1e-9:
        return table
    return tuple((thr * factor, sc) for thr, sc in table)


def higher_is_better(value: Optional[float], table: Table,
                     below: float = 0.0) -> float:
    """Оценка по убывающей таблице порогов. None -> `below`."""
    if value is None:
        return below
    for thr, sc in table:
        if value >= thr:
            return sc
    return below


def lower_is_better(value: Optional[float], table: Table,
                    above: float = 0.0) -> float:
    """Оценка по ВОЗРАСТАЮЩЕЙ таблице порогов (меньше значение — выше балл)."""
    if value is None:
        return above
    for thr, sc in table:
        if value <= thr:
            return sc
    return above


def book_score(imbalance: Optional[float]) -> float:
    """Перекос книги [−1..+1] в оценку [0..1]. Нейтральный перекос = 0.5.

    Ноль здесь означал бы «все продавцы против нас» — но перекос книги пока
    не подтверждён ничем, поэтому вето по нему не выдаётся: величина зажата
    снизу так, чтобы никогда не быть ровно нулём (см. veto_zero).
    """
    if imbalance is None:
        return 0.5
    return max(0.01, min(1.0, (imbalance + 1.0) / 2.0))


def combine(parts) -> float:
    """Взвешенное среднее оценок. `parts` — [(имя, вес, оценка), ...].

    Веса нормируются сами, поэтому задавать их можно в любых единицах.
    Все веса нулевые — считаем простое среднее, иначе делили бы на ноль.
    """
    if not parts:
        return 0.0
    wsum = sum(w for _n, w, _v in parts)
    if wsum <= 0:
        return sum(v for _n, _w, v in parts) / len(parts)
    return sum(w * v for _n, w, v in parts) / wsum
