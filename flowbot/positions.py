"""Сколько шэров у нас РЕАЛЬНО — по ответу биржи, а не по своей памяти.

Зачем это отдельно. Бот вёл учёт позиций только по собственным записям: купил
— запомнил ногу, продал — забыл. Любое расхождение с биржей оставалось
незамеченным навсегда, а расхождений хватает:

  * ордер ушёл по таймауту — мы не знаем, дошёл он или нет, и ногу НЕ
    записываем; если дошёл, шэры есть, а бот про них не подозревает;
  * ответ разобрался как отказ, а сделка на самом деле прошла;
  * продажа посчиталась удавшейся, но исполнилась лишь частично.

Итог одинаковый и самый неприятный: на Polymarket позиция висит и теряет в
цене, а бот показывает «поз —» и ничего не делает, потому что управлять он
может только тем, о чём знает.

Разбор ответа здесь такой же осторожный, как в fills.py: точную схему ответа
CLOB отсюда проверить нельзя, поэтому непонятное честно возвращается как
None («не знаю»), а не как ноль («позиций нет»). Разница принципиальна: ноль
заставил бы бота выбросить настоящую ногу.
"""
from __future__ import annotations

import math
from typing import Any, Optional

# Шэры и USDC приходят в «сырых» единицах с шестью знаками, как в ERC-20.
DECIMALS = 1_000_000.0


def shares_from_balance(resp: Any) -> Optional[float]:
    """Ответ get_balance_allowance -> сколько шэров у нас. None = не поняли."""
    if resp is None:
        return None
    if not isinstance(resp, dict):
        d = getattr(resp, "__dict__", None)
        if not isinstance(d, dict):
            return None
        resp = d

    for key in ("balance", "Balance", "amount", "size"):
        if key not in resp:
            continue
        try:
            raw = float(resp[key])
        except (TypeError, ValueError):
            return None
        if raw != raw:                      # NaN
            return None
        # Значение приходит в сырых единицах (1 шэр = 1_000_000). Дробное
        # значение меньше единицы — уже нормализованное, оставляем как есть.
        shares = raw / DECIMALS if raw >= 1.0 else raw
        # УСЕКАЕМ ВНИЗ, а не округляем. Это ответ на вопрос «сколько мы
        # можем продать», и завышать его нельзя ни на единицу: round() для
        # 67795 сырых давал 0.0678 шэра при фактических 0.067795, и ордер
        # на такую ногу отвергался с "not enough balance".
        return math.floor(shares * 10_000) / 10_000.0
    return None


def reconcile(ours: float, theirs: Optional[float],
              tol: float = 0.01) -> Optional[float]:
    """На сколько шэров разошлись мы и биржа. None = сверять не с чем.

    Положительное — у биржи БОЛЬШЕ, чем мы думаем (есть неучтённая позиция).
    Отрицательное — у нас записано больше, чем есть на самом деле (фантом).
    """
    if theirs is None:
        return None
    diff = round(theirs - ours, 4)
    return diff if abs(diff) > tol else 0.0
